long long gcd(long long a, long long b)
{
    if (a == 0)
    {
        return b;
    }
    return gcd(b % a, a);
}
void solve()
{
    long long n;
    cin >> n;
    vector<long long> arr(n);
    for (int i = 0; i < n; i++)
    {
        cin >> arr[i];
    }
    long long ans = gcd(arr[0], arr[n-1]);
    cout<<ans<<'\n';
}

